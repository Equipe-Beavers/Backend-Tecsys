    ('ALVENARIA', 'Alvenaria', 'Tijolo ou bloco cerâmico/concreto com reboco.', 7.00, 10.00, FALSE),
    ('METAL', 'Metálico', 'Galpões e coberturas metálicas.', 25.00, 30.00, FALSE),
