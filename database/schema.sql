-- Perda de um material na frequência pedida, interpolando em log(f) entre 900 e 2400 MHz.
CREATE OR REPLACE FUNCTION perda_material_db(p_codigo VARCHAR, p_frequencia_mhz DOUBLE PRECISION)
RETURNS DOUBLE PRECISION
LANGUAGE sql STABLE AS $$
    SELECT GREATEST(
        0,
        m.perda_db_900mhz
        + (m.perda_db_2400mhz - m.perda_db_900mhz)
          * LOG(GREATEST(p_frequencia_mhz, 1) / 900.0) / LOG(2400.0 / 900.0)
    )::DOUBLE PRECISION
    FROM materiais_construcao m
    WHERE m.codigo = p_codigo
$$;
