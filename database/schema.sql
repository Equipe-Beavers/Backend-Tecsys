-- Schema principal do Backend Tecsys (PostgreSQL + PostGIS).
-- Aplicar somente em banco vazio. Não atualiza bancos existentes.
-- A aplicação não executa este arquivo automaticamente.
CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS spatial_ref_sys (
  srid integer NOT NULL CHECK (srid > 0 AND srid <= 998999),
  auth_name character varying,
  auth_srid integer,
  srtext character varying,
  proj4text character varying,
  CONSTRAINT spatial_ref_sys_pkey PRIMARY KEY (srid)
);

CREATE TABLE posicoes_geograficas (
    id_posicao BIGSERIAL PRIMARY KEY,
    tipo_posicao VARCHAR(30) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    geom GEOMETRY(Point, 4674),
    municipio VARCHAR(100),
    bairro VARCHAR(100),
    data_inclusao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    data_fim TIMESTAMP NULL,
    registro_atual BOOLEAN DEFAULT TRUE,
    lote_carga VARCHAR(20)
);

CREATE INDEX idx_posicoes_geograficas_geom
ON posicoes_geograficas USING GIST (geom);

CREATE INDEX idx_posicoes_geograficas_registro_atual
ON posicoes_geograficas (registro_atual) WHERE registro_atual = TRUE;

CREATE INDEX idx_posicoes_geograficas_municipio
ON posicoes_geograficas (municipio);

CREATE TABLE tipos_dispositivos (
    id_tipo_dispositivo INT PRIMARY KEY,
    nome_dispositivo VARCHAR(100) NOT NULL,
    categoria VARCHAR(50)
);

CREATE INDEX idx_tipos_dispositivos_categoria
ON tipos_dispositivos (categoria);

CREATE TABLE postes (
    id_poste BIGSERIAL PRIMARY KEY,
    cod_id VARCHAR(50) NOT NULL,
    altura NUMERIC(4,1),
    material VARCHAR(30),
    esforco NUMERIC(6,1),
    id_posicao BIGINT NOT NULL,
    data_inclusao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    data_fim TIMESTAMP NULL,
    registro_atual BOOLEAN DEFAULT TRUE,
    lote_carga VARCHAR(20),
    CONSTRAINT fk_postes_posicao FOREIGN KEY (id_posicao) REFERENCES posicoes_geograficas (id_posicao) ON DELETE RESTRICT
);

CREATE INDEX idx_postes_posicao ON postes (id_posicao);
CREATE INDEX idx_postes_cod_id ON postes (cod_id);
CREATE INDEX idx_postes_registro_atual ON postes (registro_atual) WHERE registro_atual = TRUE;
CREATE TABLE subestacoes (
    id_subestacao BIGSERIAL PRIMARY KEY,
    cod_id VARCHAR(50) NOT NULL,
    nome VARCHAR(100),
    id_posicao BIGINT NOT NULL,
    data_inclusao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    data_fim TIMESTAMP NULL,
    registro_atual BOOLEAN DEFAULT TRUE,
    lote_carga VARCHAR(20),
    CONSTRAINT fk_subestacoes_posicao FOREIGN KEY (id_posicao) REFERENCES posicoes_geograficas (id_posicao) ON DELETE RESTRICT
);

CREATE INDEX idx_subestacoes_posicao ON subestacoes (id_posicao);
CREATE INDEX idx_subestacoes_cod_id ON subestacoes (cod_id);
CREATE INDEX idx_subestacoes_registro_atual ON subestacoes (registro_atual) WHERE registro_atual = TRUE;

CREATE TABLE dispositivos (
    id_dispositivo BIGSERIAL PRIMARY KEY,
    cod_id VARCHAR(50) NOT NULL,
    id_tipo_dispositivo INT NOT NULL,
    subestacao VARCHAR(50),
    codigo_conjunto_aneel INT,
    id_posicao BIGINT NOT NULL,
    data_inclusao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    data_fim TIMESTAMP NULL,
    registro_atual BOOLEAN DEFAULT TRUE,
    lote_carga VARCHAR(20),
    CONSTRAINT fk_dispositivos_tipo FOREIGN KEY (id_tipo_dispositivo) REFERENCES tipos_dispositivos (id_tipo_dispositivo),
    CONSTRAINT fk_dispositivos_posicao FOREIGN KEY (id_posicao) REFERENCES posicoes_geograficas (id_posicao) ON DELETE RESTRICT
);

CREATE INDEX idx_dispositivos_posicao ON dispositivos (id_posicao);
CREATE INDEX idx_dispositivos_tipo ON dispositivos (id_tipo_dispositivo);
CREATE INDEX idx_dispositivos_cod_id ON dispositivos (cod_id);
CREATE INDEX idx_dispositivos_registro_atual ON dispositivos (registro_atual) WHERE registro_atual = TRUE;
CREATE INDEX idx_dispositivos_conjunto_aneel ON dispositivos (codigo_conjunto_aneel);

CREATE TABLE municipios (
    codigo_ibge INTEGER PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    uf CHAR(2) NOT NULL
);

CREATE INDEX idx_municipios_uf ON municipios (uf);

CREATE TABLE usuarios (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) UNIQUE NOT NULL,
  email VARCHAR(255) UNIQUE NOT NULL,
  senha_hash VARCHAR(255) NOT NULL,
  criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  atualizado_em TIMESTAMP
);

CREATE TABLE perfis_rf (
  id_perfil_rf BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL,
  nome VARCHAR(150) NOT NULL,
  frequencia_mhz DECIMAL(10,3) NOT NULL,
  potencia_transmissao_dbm DECIMAL(8,3) NOT NULL,
  sensibilidade_recepcao_dbm DECIMAL(8,3) NOT NULL,
  altura_gateway_m DECIMAL(8,2),
  altura_dispositivo_m DECIMAL(8,2),
  capacidade_max_equipamentos INT,
  atenuacao_adicional_db DECIMAL(8,3),
  considera_relevo BOOLEAN NOT NULL DEFAULT TRUE,
  considera_vegetacao BOOLEAN NOT NULL DEFAULT TRUE,
  considera_edificacoes BOOLEAN NOT NULL DEFAULT TRUE,
  considera_antenas BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  atualizado_em TIMESTAMP,
  CONSTRAINT fk_perfis_rf_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario)
);

CREATE INDEX idx_perfis_rf_usuario ON perfis_rf (id_usuario);

CREATE TABLE criterios_instalacao (
  id_criterio_instalacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL,
  nome VARCHAR(150) NOT NULL,
  tipos_elementos_permitidos JSONB,
  tipos_elementos_proibidos JSONB,
  requer_alimentacao_eletrica BOOLEAN,
  distancia_minima_ativos_m DECIMAL(12,2),
  distancia_maxima_ativos_m DECIMAL(12,2),
  CONSTRAINT criterios_instalacao_distancias_validas CHECK (distancia_minima_ativos_m IS NULL OR (distancia_minima_ativos_m >= 0 AND (distancia_maxima_ativos_m IS NULL OR distancia_minima_ativos_m <= distancia_maxima_ativos_m))),
  CONSTRAINT criterios_instalacao_distancias_faixa CHECK (
    (distancia_minima_ativos_m IS NULL OR distancia_minima_ativos_m BETWEEN 10 AND 500)
    AND (distancia_maxima_ativos_m IS NULL OR distancia_maxima_ativos_m BETWEEN 10 AND 500)
  ),
  limite_gateways INT,
  relevo JSONB,
  vegetacoes JSONB,
  edificacoes JSONB,
  antenas JSONB,
  criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  atualizado_em TIMESTAMP,
  CONSTRAINT fk_criterios_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario)
);

CREATE INDEX idx_criterios_instalacao_usuario ON criterios_instalacao (id_usuario);

CREATE TABLE estudos (
  id_estudo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL,
  id_perfil_rf BIGINT NOT NULL,
  id_criterio_instalacao BIGINT NOT NULL,
  tipo_delimitacao VARCHAR(30) NOT NULL,
  uf VARCHAR(2),
  municipio VARCHAR(120),
  bairro VARCHAR(120),
  geom GEOMETRY(Geometry, 4674),
  nome VARCHAR(150) NOT NULL,
  descricao TEXT,
  distribuidora VARCHAR(150),
  versao_bdgd VARCHAR(100),
  nome_base_externa VARCHAR(255),
  tipos_ativo_selecionados JSONB,
  status VARCHAR(30) NOT NULL,
  criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  atualizado_em TIMESTAMP,
  CONSTRAINT fk_estudos_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario),
  CONSTRAINT fk_estudos_perfil_rf FOREIGN KEY (id_perfil_rf) REFERENCES perfis_rf (id_perfil_rf),
  CONSTRAINT fk_estudos_criterio_instalacao FOREIGN KEY (id_criterio_instalacao) REFERENCES criterios_instalacao (id_criterio_instalacao)
);

CREATE INDEX idx_estudos_usuario ON estudos (id_usuario);
CREATE INDEX idx_estudos_perfil_rf ON estudos (id_perfil_rf);
CREATE INDEX idx_estudos_criterio ON estudos (id_criterio_instalacao);
CREATE INDEX idx_estudos_status ON estudos (status);
CREATE INDEX idx_estudos_geom ON estudos USING GIST (geom);

CREATE TABLE estudo_pontos (
  id_estudo_ponto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_estudo BIGINT NOT NULL,
  origem VARCHAR(20) NOT NULL,
  id_ativo_bdgd VARCHAR(60),
  tipo_ativo VARCHAR(60),
  rotulo VARCHAR(150),
  papel VARCHAR(20) NOT NULL,
  prioridade VARCHAR(20),
  latitude DECIMAL(10,7) NOT NULL,
  longitude DECIMAL(10,7) NOT NULL,
  atributos JSONB,
  geom GEOMETRY(Point, 4674),
  criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_estudo_pontos_estudo FOREIGN KEY (id_estudo) REFERENCES estudos (id_estudo)
);

CREATE INDEX idx_estudo_pontos_estudo ON estudo_pontos (id_estudo);
CREATE INDEX idx_estudo_pontos_ativo_bdgd ON estudo_pontos (id_ativo_bdgd);
CREATE INDEX idx_estudo_pontos_geom ON estudo_pontos USING GIST (geom);

CREATE TABLE cenarios (
  id_cenario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_estudo BIGINT NOT NULL,
  id_cenario_base BIGINT,
  nome VARCHAR(150) NOT NULL,
  descricao TEXT,
  objetivo VARCHAR(40),
  status VARCHAR(30) NOT NULL,
  quantidade_gateways INT,
  pontos_interesse INT,
  pontos_cobertos INT,
  pontos_nao_cobertos INT,
  percentual_cobertura DECIMAL(5,2),
  capacidade_utilizada_media_pct DECIMAL(5,2),
  mancha_consolidada GEOMETRY(MultiPolygon, 4674),
  executado_em TIMESTAMP,
  criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  atualizado_em TIMESTAMP,
  CONSTRAINT fk_cenarios_estudo FOREIGN KEY (id_estudo) REFERENCES estudos (id_estudo),
  CONSTRAINT fk_cenarios_base FOREIGN KEY (id_cenario_base) REFERENCES cenarios (id_cenario)
);

CREATE INDEX idx_cenarios_estudo ON cenarios (id_estudo);
CREATE INDEX idx_cenarios_base ON cenarios (id_cenario_base);
CREATE INDEX idx_cenarios_mancha ON cenarios USING GIST (mancha_consolidada);

CREATE TABLE cenario_gateways (
  id_cenario_gateway BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cenario BIGINT NOT NULL,
  id_estudo_ponto BIGINT NOT NULL,
  ordem INT,
  quantidade_pontos_atendidos INT,
  capacidade_utilizada_pct DECIMAL(5,2),
  parametros_calculo JSONB,
  mancha_cobertura GEOMETRY(Polygon, 4674),
  CONSTRAINT fk_cenario_gateways_cenario FOREIGN KEY (id_cenario) REFERENCES cenarios (id_cenario),
  CONSTRAINT fk_cenario_gateways_ponto FOREIGN KEY (id_estudo_ponto) REFERENCES estudo_pontos (id_estudo_ponto)
);

CREATE INDEX idx_cenario_gateways_cenario ON cenario_gateways (id_cenario);
CREATE INDEX idx_cenario_gateways_ponto ON cenario_gateways (id_estudo_ponto);
CREATE INDEX idx_cenario_gateways_mancha ON cenario_gateways USING GIST (mancha_cobertura);

CREATE TABLE cenario_atendimentos (
  id_atendimento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cenario_gateway BIGINT NOT NULL,
  id_estudo_ponto BIGINT NOT NULL,
  distancia_m DECIMAL(12,2),
  nivel_sinal_estimado_dbm DECIMAL(8,3),
  criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_atendimentos_gateway FOREIGN KEY (id_cenario_gateway) REFERENCES cenario_gateways (id_cenario_gateway),
  CONSTRAINT fk_atendimentos_ponto FOREIGN KEY (id_estudo_ponto) REFERENCES estudo_pontos (id_estudo_ponto)
);

CREATE UNIQUE INDEX idx_cenario_atendimentos_unique ON cenario_atendimentos (id_cenario_gateway, id_estudo_ponto);
CREATE INDEX idx_cenario_atendimentos_gateway ON cenario_atendimentos (id_cenario_gateway);
CREATE INDEX idx_cenario_atendimentos_ponto ON cenario_atendimentos (id_estudo_ponto);

