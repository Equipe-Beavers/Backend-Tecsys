CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS antenas_anatel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key TEXT NOT NULL UNIQUE,
    uid TEXT,
    num_estacao TEXT,
    entidade TEXT,
    servico TEXT,
    uf CHAR(2),
    municipio TEXT,
    endereco TEXT,
    tecnologia TEXT,
    tipo_estacao TEXT,
    tipo_antena TEXT,
    frequencia_tx_mhz DOUBLE PRECISION,
    frequencia_rx_mhz DOUBLE PRECISION,
    azimute_graus DOUBLE PRECISION,
    altura_antena_m DOUBLE PRECISION,
    potencia_transmissor_w DOUBLE PRECISION,
    data_licenciamento DATE,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    geom GEOMETRY(Point, 4674) NOT NULL,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_antenas_anatel_geom
    ON antenas_anatel USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_antenas_anatel_uf_municipio
    ON antenas_anatel (uf, municipio);
CREATE INDEX IF NOT EXISTS idx_antenas_anatel_num_estacao
    ON antenas_anatel (num_estacao);
