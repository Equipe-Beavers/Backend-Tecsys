CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS public.emissoes_anatel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key TEXT NOT NULL UNIQUE,
    uid TEXT,
    fonte_dados TEXT NOT NULL DEFAULT 'LICENCIADAS',
    status TEXT,
    entidade TEXT,
    fistel TEXT,
    num_servico TEXT,
    ato_rf TEXT,
    num_estacao TEXT,
    endereco TEXT,
    complemento TEXT,
    uf CHAR(2),
    municipio TEXT,
    emissao TEXT,
    tecnologia TEXT,
    tipo_tecnologia TEXT,
    meio_acesso TEXT,
    frequencia_tx_mhz DOUBLE PRECISION,
    frequencia_rx_mhz DOUBLE PRECISION,
    azimute_graus DOUBLE PRECISION,
    tipo_estacao TEXT,
    class_infra_fisica TEXT,
    compartilhamento_infra_fisica TEXT,
    tipo_antena TEXT,
    homologacao_antena TEXT,
    ganho_antena DOUBLE PRECISION,
    frente_costas DOUBLE PRECISION,
    angulo_meia_potencia_graus DOUBLE PRECISION,
    elevacao_graus DOUBLE PRECISION,
    polarizacao TEXT,
    altura_antena_m DOUBLE PRECISION,
    homologacao_transmissor TEXT,
    potencia_transmissor_w DOUBLE PRECISION,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    geom geometry(Point, 4674) NOT NULL,
    codigo_tfi TEXT,
    data_licenciamento DATE,
    data_primeiro_licenciamento DATE,
    rede TEXT,
    data_validade DATE,
    fistel_associado TEXT,
    nome_entidade_associado TEXT,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_emissoes_anatel_geom
    ON public.emissoes_anatel USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_emissoes_anatel_tx
    ON public.emissoes_anatel (frequencia_tx_mhz);
CREATE INDEX IF NOT EXISTS idx_emissoes_anatel_rx
    ON public.emissoes_anatel (frequencia_rx_mhz);
CREATE INDEX IF NOT EXISTS idx_emissoes_anatel_uf_municipio
    ON public.emissoes_anatel (uf, municipio);
CREATE INDEX IF NOT EXISTS idx_emissoes_anatel_num_estacao
    ON public.emissoes_anatel (num_estacao);
CREATE INDEX IF NOT EXISTS idx_emissoes_anatel_fonte
    ON public.emissoes_anatel (fonte_dados);
